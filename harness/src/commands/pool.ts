/** The card pool: `pool` lists every precon with the set files it needs
 *  and its qualification status, `pool --qualify` (re)qualifies decks, and
 *  `smoke` fuzzes the seat interface across the pool with the mock model. */
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { auditGameLog, buildCardSideMap } from "../audit.js";
import { loadCardData } from "../carddata.js";
import {
  checkPool,
  hardErrors,
  loadPoolManifest,
  POOL_MANIFEST,
  type PoolManifest,
  type QualificationGame,
} from "../cardpool.js";
import { launchBrowser, runGame } from "../game.js";
import { runLLMGame, type SeatMode } from "../llmgame.js";
import { loadPrecon } from "../precons.js";
import type { Command, Context } from "./args.js";

async function preconNames(repoRoot: string): Promise<string[]> {
  return (await readdir(join(repoRoot, "precons")))
    .filter((f) => f.endsWith(".js"))
    .map((f) => f.replace(/\.js$/, ""))
    .sort();
}

const REFERENCE = { corp: "Gateway Corp", runner: "Gateway Runner" };

/** Per deck: three rules-vs-rules games against the Gateway opponent (no-
 *  cheating checker on, conservation audit run) and one mock game in the
 *  deck's own seat. A deck qualifies only if every game completes with no
 *  hard error, leak, audit finding or invalid record. The manifest is
 *  rewritten after every deck; `--resume` keeps decks already qualified on
 *  the same seeds. A hang is caught by the no-progress stall check, so the
 *  whole-game limit is generous: long games on a loaded machine must not
 *  read as engine defects. */
async function qualify({ repoRoot, outDir, args }: Context, names: string[]): Promise<number> {
  const seeds = args.str("seeds", "1,2,3").split(",").map((x) => parseInt(x, 10));
  const jobs = Math.max(1, args.int("jobs", 2));
  const timeoutMs = 900_000;
  const only = args.str("only", "");
  const resume = args.has("resume");
  const cards = await loadCardData(repoRoot);
  const cardSide = await buildCardSideMap(repoRoot);
  const existing = await loadPoolManifest(repoRoot);
  const manifest: PoolManifest = {
    comment:
      "Card-pool qualification, generated by `cli.ts pool --qualify`. Decks with " +
      "qualified=false hit engine defects (crash, stall, error) or harness checks and are " +
      "refused by llm-game, run-match and the MCP server unless --allow-unqualified.",
    generated: new Date().toISOString().slice(0, 10),
    referenceOpponents: REFERENCE,
    seeds,
    decks: existing && (only || resume) ? { ...existing.decks } : {},
  };
  const sameSeeds = (games: QualificationGame[]): boolean =>
    JSON.stringify(games.filter((g) => g.kind === "rules").map((g) => g.seed)) === JSON.stringify(seeds);
  const todo = names.filter((n) => !(resume && manifest.decks[n] && sameSeeds(manifest.decks[n]!.games)));
  if (resume) console.log(`resuming: ${names.length - todo.length} decks kept, ${todo.length} to run`);
  const writeManifest = async (): Promise<void> => {
    const decks = Object.fromEntries(Object.entries(manifest.decks).sort(([a], [b]) => a.localeCompare(b)));
    await writeFile(join(repoRoot, POOL_MANIFEST), JSON.stringify({ ...manifest, decks }, null, 1) + "\n");
  };
  const crashed = (kind: QualificationGame["kind"], seed: number, opponent: string, err: unknown): QualificationGame => ({
    kind, seed, opponent, status: "crashed", winner: null, hardErrors: 1, lint: 0,
    invariantViolations: 0, auditFindings: null, invalidRecords: null,
    firstProblem: `harness exception: ${String(err instanceof Error ? err.message : err).slice(0, 140)}`,
  });
  const browser = await launchBrowser();
  const qualifyDeck = async (name: string): Promise<void> => {
    const deck = await loadPrecon(repoRoot, name);
    const side = cards.get(deck.identity)?.side === "corp" ? "corp" : "runner";
    const check = await checkPool(repoRoot, [deck]);
    const games: QualificationGame[] = [];
    const opponent = side === "corp" ? REFERENCE.runner : REFERENCE.corp;
    const corpPrecon = side === "corp" ? name : opponent;
    const runnerPrecon = side === "corp" ? opponent : name;
    if (check.missing.length === 0) {
      for (const seed of seeds) {
        try {
          const rec = await runGame(
            { repoRoot, seed, corpPrecon, runnerPrecon, extraParams: "&invariant=1", timeoutMs },
            browser
          );
          const hard = hardErrors(rec.errors);
          const audit = await auditGameLog(name, rec.log, cardSide);
          const auditFindings = audit.issues.length + audit.unknownCreditLines.length;
          const v = rec.invariantViolations ?? [];
          games.push({
            kind: "rules", seed, opponent, status: rec.status, winner: rec.winner,
            hardErrors: hard.length, lint: rec.errors.length - hard.length,
            invariantViolations: v.length, auditFindings, invalidRecords: null,
            firstProblem:
              rec.status !== "completed"
                ? `game ${rec.status}${hard[0] ? `: ${hard[0].slice(0, 140)}` : ""}`
                : hard[0]?.slice(0, 160) ??
                  (v[0] ? `leak: ${JSON.stringify(v[0]).slice(0, 140)}` : null) ??
                  (auditFindings
                    ? `audit: ${(audit.issues[0]?.detail ?? audit.unknownCreditLines[0]?.text ?? "").slice(0, 140)}`
                    : null),
          });
        } catch (err) {
          games.push(crashed("rules", seed, opponent, err));
        }
      }
      const seed = seeds[0]!;
      try {
        const rec = await runLLMGame({
          repoRoot, seed, corpPrecon, runnerPrecon, seat: side, model: "mock",
          rulesSource: "digest", profile: "neutral", reasoningStyle: "brief",
          debrief: false, frames: false, extraParams: "&invariant=1",
          outDir: join(outDir, "qualify"),
        });
        const hard = hardErrors(rec.errors);
        const v = rec.invariantViolations ?? [];
        games.push({
          kind: "llm-mock", seed, opponent, status: rec.status, winner: rec.winner,
          hardErrors: hard.length, lint: rec.errors.length - hard.length,
          invariantViolations: v.length, auditFindings: null, invalidRecords: rec.invalidRecords,
          firstProblem:
            rec.status !== "completed"
              ? `mock ${side}-seat game ${rec.status}${hard[0] ? `: ${hard[0].slice(0, 140)}` : ""}`
              : hard[0]?.slice(0, 160) ??
                (v[0] ? `leak: ${JSON.stringify(v[0]).slice(0, 140)}` : null) ??
                (rec.invalidRecords ? `${rec.invalidRecords} invalid records` : null),
        });
      } catch (err) {
        games.push(crashed("llm-mock", seed, opponent, err));
      }
    }
    const qualified =
      check.missing.length === 0 &&
      games.every(
        (g) => g.status === "completed" && g.hardErrors === 0 && g.invariantViolations === 0 && !g.auditFindings && !g.invalidRecords
      );
    manifest.decks[name] = { side, sets: check.sets, qualified, games };
    await writeManifest();
    console.log(
      `${qualified ? "✓" : "✗"} ${side.padEnd(6)} ${name.padEnd(40)} ` +
        (qualified ? "" : games.find((g) => g.firstProblem)?.firstProblem ?? `${check.missing.length} unimplemented card(s)`)
    );
  };
  const queue = [...todo];
  await Promise.all(
    Array.from({ length: Math.min(jobs, queue.length) }, async () => {
      for (let name = queue.shift(); name !== undefined; name = queue.shift()) await qualifyDeck(name);
    })
  );
  await browser.close();
  await writeManifest();
  const all = Object.values(manifest.decks);
  console.log(`\nqualified ${all.filter((d) => d.qualified).length}/${all.length} decks → ${POOL_MANIFEST}`);
  return 0;
}

export const poolCommand: Command = async (ctx) => {
  const { repoRoot, args } = ctx;
  const only = args.str("only", "");
  const names = (await preconNames(repoRoot)).filter((n) => !only || n === only);
  if (args.has("qualify")) return qualify(ctx, names);
  const cards = await loadCardData(repoRoot);
  const manifest = await loadPoolManifest(repoRoot);
  for (const side of ["corp", "runner"]) {
    console.log(`\n${side.toUpperCase()} precons (✓ qualified, ✗ failed qualification, ? not qualified yet):`);
    for (const name of names) {
      const deck = await loadPrecon(repoRoot, name);
      if ((cards.get(deck.identity)?.side ?? "") !== side) continue;
      const check = await checkPool(repoRoot, [deck]);
      const q = manifest?.decks[name];
      const mark = check.missing.length ? "✗" : q ? (q.qualified ? "✓" : "✗") : "?";
      const why = q && !q.qualified ? ` — ${q.games.find((g) => g.firstProblem)?.firstProblem ?? ""}` : "";
      console.log(
        `  ${mark} ${name.padEnd(40)} ${check.sets.length ? check.sets.join("+") : "base pool"}` +
          (check.missing.length ? ` — ${check.missing.length} unimplemented card(s)` : why)
      );
    }
  }
  return 0;
};

/** Pairs every Corp precon with a Runner precon (cycling the shorter list)
 *  and plays each pairing rules-vs-rules (state invariant) and with the
 *  mock in each requested seat mode (menu invariant, multi-select adapter,
 *  record validation). Skips decks that failed qualification unless
 *  --allow-unqualified: smoke tests the harness, not the engine. */
export const smokeCommand: Command = async ({ repoRoot, outDir, args }) => {
  const pool = args.str("pool", "all"); // all | base | extended
  const modes = args.str("seats", "rules,runner,corp,both").split(",");
  const limit = args.int("limit", 0);
  const manifest = await loadPoolManifest(repoRoot);
  const allowUnqualified = args.flag("allow-unqualified");
  const cards = await loadCardData(repoRoot);
  const bySide: Record<"corp" | "runner", string[]> = { corp: [], runner: [] };
  const skipped: string[] = [];
  for (const name of await preconNames(repoRoot)) {
    const deck = await loadPrecon(repoRoot, name);
    const check = await checkPool(repoRoot, [deck]);
    if (check.missing.length) continue;
    const extended = check.sets.length > 0;
    if ((pool === "base" && extended) || (pool === "extended" && !extended)) continue;
    if (!allowUnqualified && manifest?.decks[name]?.qualified === false) {
      skipped.push(name);
      continue;
    }
    const side = cards.get(deck.identity)?.side;
    if (side === "corp" || side === "runner") bySide[side].push(name);
  }
  const n = Math.max(bySide.corp.length, bySide.runner.length);
  let pairs: [string, string][] = Array.from({ length: n }, (_, i) => [
    bySide.corp[i % bySide.corp.length]!,
    bySide.runner[i % bySide.runner.length]!,
  ]);
  if (limit > 0) pairs = pairs.slice(0, limit);
  if (skipped.length) console.log(`skipping ${skipped.length} deck(s) that failed qualification: ${skipped.join(", ")}`);
  const lintCount = (errors: string[]): number => errors.length - hardErrors(errors).length;
  const browser = modes.includes("rules") ? await launchBrowser() : null;
  let failures = 0;
  let games = 0;
  for (const [i, [c, r]] of pairs.entries()) {
    const seed = args.seed + i;
    for (const mode of modes) {
      games++;
      let ok: boolean;
      let line: string;
      if (mode === "rules") {
        const rec = await runGame({ repoRoot, seed, corpPrecon: c, runnerPrecon: r, extraParams: "&invariant=1" }, browser!);
        const v = rec.invariantViolations ?? [];
        const hard = hardErrors(rec.errors);
        ok = rec.status === "completed" && hard.length === 0 && v.length === 0;
        line = `${rec.status} ${rec.winner ?? "-"} errors=${hard.length} lint=${lintCount(rec.errors)} invariant=${rec.invariantChecks ?? 0}/${v.length}`;
        if (!ok) console.log("   ", JSON.stringify([...hard.slice(0, 3), ...v.slice(0, 3)]).slice(0, 400));
      } else {
        const rec = await runLLMGame({
          repoRoot, seed, corpPrecon: c, runnerPrecon: r, seat: mode as SeatMode, model: "mock",
          rulesSource: "digest", profile: "neutral", reasoningStyle: "brief",
          debrief: false, frames: false, extraParams: "&invariant=1",
          outDir: join(outDir, "smoke"),
        });
        const v = rec.invariantViolations ?? [];
        const hard = hardErrors(rec.errors);
        ok = rec.status === "completed" && hard.length === 0 && rec.invalidRecords === 0 && v.length === 0;
        line =
          `${rec.status} ${rec.winner ?? "-"} errors=${hard.length} lint=${lintCount(rec.errors)} ` +
          `invalid=${rec.invalidRecords} invariant=${rec.invariantChecks ?? 0}/${v.length} ` +
          `multiSelects=${rec.multiSelects} neutralized=${rec.neutralizedReads}`;
        if (!ok) console.log("   ", JSON.stringify([...hard.slice(0, 3), ...v.slice(0, 3)]).slice(0, 400));
      }
      if (!ok) failures++;
      console.log(`${ok ? "ok  " : "FAIL"} s${seed} ${mode.padEnd(6)} ${c} vs ${r}: ${line}`);
    }
  }
  if (browser) await browser.close();
  console.log(failures === 0 ? `SMOKE: all ${games} games clean` : `SMOKE: ${failures}/${games} FAILED`);
  return failures === 0 ? 0 : 1;
};
